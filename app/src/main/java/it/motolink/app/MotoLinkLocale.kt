/**
 * vc29 TEST: system-locale UI layer.
 *
 * MotoLink keeps technical logs stable for support, while user-facing strings are rendered
 * according to the phone language. Italian is preserved, English is the fallback for every
 * unsupported locale, and dedicated Russian / Simplified Chinese packs are provided.
 */
object MotoLinkLocale {
    private fun language(): String {
        val locale = if (Build.VERSION.SDK_INT >= 24) {
            android.os.LocaleList.getDefault().get(0)
        } else {
            @Suppress("DEPRECATION")
            Locale.getDefault()
        }
        return locale.language.lowercase(Locale.ROOT)
    }

    fun t(context: Context, raw: String): String {
        if (raw.isBlank()) return raw
        val lang = language()
        if (lang == "it") return raw
        val key = raw.trim()
        val exact = when (lang) {
            "ru" -> RU[key]
            "zh" -> ZH[key]
            else -> EN[key]
        }
        if (exact != null) return preserveOuterWhitespace(raw, key, exact)
        return dynamic(raw, lang)
    }

    private fun preserveOuterWhitespace(raw: String, key: String, translated: String): String {
        val prefix = raw.substringBefore(key)
        val suffix = raw.substringAfter(key, "")
        return prefix + translated + suffix
    }

    private fun dynamic(raw: String, lang: String): String {
        val tr = when (lang) {
            "ru" -> ::ruDynamic
            "zh" -> ::zhDynamic
            else -> ::enDynamic
        }
        return tr(raw)
    }

